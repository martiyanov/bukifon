namespace {
bool isCyrillicIndex(uint32_t cp, int* index) {
  if (cp >= 0x0410 && cp <= 0x042F) {
    *index = static_cast<int>(cp - 0x0410);
    return true;
  }
  if (cp >= 0x0430 && cp <= 0x044F) {
    *index = 32 + static_cast<int>(cp - 0x0430);
    return true;
  }
  if (cp == 0x0401) {
    *index = 64;
    return true;
  }
  if (cp == 0x0451) {
    *index = 65;
    return true;
  }
  return false;
}
}  // namespace

const uint8_t* uiFontGlyph(uint32_t codepoint) {
  if (codepoint >= 32 && codepoint <= 127) return kFont6x8[codepoint - 32];
  int index = 0;
  if (isCyrillicIndex(codepoint, &index)) return kCyrillic6x8[index];
  if (codepoint == 0x00B7 || codepoint == 0x2014 || codepoint == 0x2013) {
    return kFont6x8[static_cast<int>('-') - 32];
  }
  return nullptr;
}

bool uiFontHasGlyph(uint32_t codepoint) { return uiFontGlyph(codepoint) != nullptr; }

int uiUtf8Codepoints(const char* text) {
  if (!text) return 0;
  int count = 0;
  for (const unsigned char* p = reinterpret_cast<const unsigned char*>(text); *p; ++p) {
    if ((*p & 0xC0) != 0x80) ++count;
  }
  return count;
}

